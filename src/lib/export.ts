function generateBRDContent(brd: BRDResult): string {
  let html = `<h1>${brd.overview.projectName}</h1>`;
  html += `<h2>Project Overview</h2>`;
  html += `<p><strong>Description:</strong> ${brd.overview.description}</p>`;
  html += `<p><strong>Target Users:</strong> ${brd.overview.targetUsers}</p>`;
  html += `<p><strong>Business Value:</strong> ${brd.overview.businessValue}</p>`;

  if (brd.objectives?.length) {
    html += `<h2>Business Objectives</h2><ul>`;
    brd.objectives.forEach(o => { html += `<li>${o}</li>`; });
    html += `</ul>`;
  }

  html += `<h2>Functional Requirements</h2><table><tr><th>#</th><th>Requirement</th><th>Description</th><th>Priority</th></tr>`;
  brd.functionalRequirements?.forEach?.((r: any, i: number) => {
    html += `<tr><td>${i + 1}</td><td>${r.name}</td><td>${r.description}</td><td class="${r.priority?.toLowerCase()}">${r.priority}</td></tr>`;
  });
  html += `</table>`;

  html += `<h2>Non-Functional Requirements</h2><table><tr><th>#</th><th>Requirement</th><th>Category</th><th>Description</th></tr>`;
  brd.nonFunctionalRequirements?.forEach?.((r: any, i: number) => {
    html += `<tr><td>${i + 1}</td><td>${r.name}</td><td>${r.category}</td><td>${r.description}</td></tr>`;
  });
  html += `</table>`;

  html += `<h2>User Stories</h2>`;
  brd.userStories?.forEach?.((s: any) => {
    html += `<h3>${s.id}</h3><p>${s.story}</p><p><strong>Acceptance Criteria:</strong></p><ul>`;
    s.acceptance?.forEach?.((a: string) => { html += `<li>${a}</li>`; });
    html += `</ul>`;
  });

  html += `<h2>User Roles</h2><table><tr><th>Role</th><th>Description</th><th>Permissions</th></tr>`;
  brd.userRoles?.forEach?.((r: any) => {
    html += `<tr><td>${r.role}</td><td>${r.description}</td><td>${r.permissions?.join(', ')}</td></tr>`;
  });
  html += `</table>`;

  html += `<h2>Architecture</h2><p><strong>Components:</strong></p><ul>`;
  brd.architecture?.components?.forEach?.((c: string) => { html += `<li>${c}</li>`; });
  html += `</ul><p><strong>Data Flow:</strong> ${brd.architecture?.dataFlow || ''}</p>`;

  html += `<h2>Technology Stack</h2><table><tr><th>Layer</th><th>Technologies</th></tr>`;
  html += `<tr><td>Frontend</td><td>${brd.techStack?.frontend?.join(', ')}</td></tr>`;
  html += `<tr><td>Backend</td><td>${brd.techStack?.backend?.join(', ')}</td></tr>`;
  html += `<tr><td>Database</td><td>${brd.techStack?.database?.join(', ')}</td></tr>`;
  html += `<tr><td>Third Party</td><td>${brd.techStack?.thirdParty?.join(', ')}</td></tr></table>`;

  html += `<h2>Project Timeline</h2>`;
  brd.timeline?.forEach?.((p: any) => {
    html += `<h3>${p.phase} (${p.duration})</h3><ul>`;
    p.tasks?.forEach?.((t: string) => { html += `<li>${t}</li>`; });
    html += `</ul>`;
  });

  html += `<h2>Risk Analysis</h2><table><tr><th>Risk</th><th>Impact</th><th>Mitigation</th></tr>`;
  brd.riskAnalysis?.forEach?.((r: any) => {
    html += `<tr><td>${r.risk}</td><td class="${r.impact?.toLowerCase()}">${r.impact}</td><td>${r.mitigation}</td></tr>`;
  });
  html += `</table>`;

  html += `<h2>Success Metrics</h2><table><tr><th>Metric</th><th>Target</th></tr>`;
  brd.successMetrics?.forEach?.((m: any) => {
    html += `<tr><td>${m.metric}</td><td>${m.target}</td></tr>`;
  });
  html += `</table>`;

  return html;
}

function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
