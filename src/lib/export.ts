import type { BRDResult } from './generate';

export function exportToMarkdown(brd: BRDResult): string {
  let md = `# ${brd.overview.projectName}\n\n`;
  md += `## Project Overview\n\n`;
  md += `**Description:** ${brd.overview.description}\n\n`;
  md += `**Target Users:** ${brd.overview.targetUsers}\n\n`;
  md += `**Business Value:** ${brd.overview.businessValue}\n\n`;

  md += `## Business Objectives\n\n`;
  brd.objectives?.forEach?.((obj: string) => { md += `- ${obj}\n`; });
  md += '\n';

  md += `## Functional Requirements\n\n`;
  md += `| # | Requirement | Description | Priority |\n`;
  md += `|---|-------------|-------------|----------|\n`;
  brd.functionalRequirements?.forEach?.((req: any, i: number) => {
    md += `| ${i + 1} | ${req.name} | ${req.description} | ${req.priority} |\n`;
  });
  md += '\n';

  md += `## Non-Functional Requirements\n\n`;
  md += `| # | Requirement | Category | Description |\n`;
  md += `|---|------------|----------|-------------|\n`;
  brd.nonFunctionalRequirements?.forEach?.((req: any, i: number) => {
    md += `| ${i + 1} | ${req.name} | ${req.category} | ${req.description} |\n`;
  });
  md += '\n';

  md += `## User Stories\n\n`;
  brd.userStories?.forEach?.((story: any) => {
    md += `### ${story.id}\n\n`;
    md += `${story.story}\n\n`;
    md += `**Acceptance Criteria:**\n`;
    story.acceptance?.forEach?.((acc: string) => { md += `- ${acc}\n`; });
    md += '\n';
  });

  md += `## User Roles\n\n`;
  md += `| Role | Description | Permissions |\n`;
  md += `|------|-------------|-------------|\n`;
  brd.userRoles?.forEach?.((role: any) => {
    md += `| ${role.role} | ${role.description} | ${role.permissions?.join(', ')} |\n`;
  });
  md += '\n';

  md += `## Architecture\n\n`;
  md += `**Components:**\n`;
  brd.architecture?.components?.forEach?.((comp: string) => { md += `- ${comp}\n`; });
  md += `\n**Data Flow:** ${brd.architecture?.dataFlow || ''}\n\n`;

  md += `## Technology Stack\n\n`;
  md += `| Layer | Technologies |\n`;
  md += `|-------|-------------|\n`;
  md += `| Frontend | ${brd.techStack?.frontend?.join(', ')} |\n`;
  md += `| Backend | ${brd.techStack?.backend?.join(', ')} |\n`;
  md += `| Database | ${brd.techStack?.database?.join(', ')} |\n`;
  md += `| Third Party | ${brd.techStack?.thirdParty?.join(', ')} |\n\n`;

  md += `## Project Timeline\n\n`;
  brd.timeline?.forEach?.((phase: any) => {
    md += `### ${phase.phase} (${phase.duration})\n\n`;
    phase.tasks?.forEach?.((task: string) => { md += `- ${task}\n`; });
    md += '\n';
  });

  md += `## Risk Analysis\n\n`;
  md += `| Risk | Impact | Mitigation |\n`;
  md += `|------|--------|------------|\n`;
  brd.riskAnalysis?.forEach?.((risk: any) => {
    md += `| ${risk.risk} | ${risk.impact} | ${risk.mitigation} |\n`;
  });
  md += '\n';

  md += `## Success Metrics\n\n`;
  md += `| Metric | Target |\n`;
  md += `|--------|--------|\n`;
  brd.successMetrics?.forEach?.((metric: any) => {
    md += `| ${metric.metric} | ${metric.target} |\n`;
  });
  md += '\n';

  md += `---\n*Generated by AutoBRD AI*\n`;

  return md;
}

export function downloadMarkdown(brd: BRDResult) {
  const md = exportToMarkdown(brd);
  downloadFile(md, `${brd.overview.projectName.replace(/\s+/g, '_')}_BRD.md`, 'text/markdown');
}

export function downloadPDF(brd: BRDResult) {
  // Generate a printable HTML that can be saved as PDF
  const html = generatePrintableHTML(brd);
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const w = window.open(url, '_blank');
  if (w) {
    w.onload = () => {
      w.print();
    };
  }
}

export function downloadDOCX(brd: BRDResult) {
  // As a fallback, generate rich HTML that Word can open
  const html = generateDocxHTML(brd);
  downloadFile(html, `${brd.overview.projectName.replace(/\s+/g, '_')}_BRD.doc`, 'application/msword');
}

